#!/usr/bin/env python3
"""Generate paper/numbers.typ from results/results.json. Nothing hand-typed.

Run after emit_results.py. Every figure the paper prints is defined here, so a re-run of
the pipeline cannot leave a stale statistic in the prose.

Typst naming constraints worth remembering: identifiers may not contain digits adjacent to
letters in ways that parse oddly, and a hyphen inside an interpolation is read as
subtraction — the paper writes `#var#[-word]` where a literal hyphen must follow a value.
Every name defined here is lowercase alphabetic for that reason.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = json.load(open(os.path.join(HERE, "results", "results.json")))
OUT = os.path.join(HERE, "paper", "numbers.typ")
os.makedirs(os.path.dirname(OUT), exist_ok=True)

L = [
    "// GENERATED by emit_numbers.py from results/results.json — do not edit by hand.",
    "// Every statistic quoted in the paper is defined here, so nothing is transcribed.",
    "",
]


def s(name, val):
    L.append(f'#let {name} = "{val}"')


def n(name, val):
    """Integer with thousands separators."""
    s(name, f"{val:,}")


s("generated", RES["generated_utc"])
s("nartifacts", RES["n_artifacts"])
L.append("")

# ---------------------------------------------------------------- geometry
g = RES["geometry"]
L.append("// --- geometry ---")
n("hidold", g["hidden_old"])
n("hidnew", g["hidden_new"])
n("hidadded", g["hidden_added"])
n("ballast", g["ballast_dims"])
n("slots", g["chip_slots"])
n("widthstated", g["width_stated_added"])
n("widthresidual", g["width_residual"])
n("headmultnew", g["hidden_new_over_head_dim"])
n("headmultold", g["hidden_old_over_head_dim"])
n("layerstotal", g["layers_total"])
n("layerschip", g["layers_chip"])
n("layersqwen", g["layers_qwen"])
n("nlinear", g["n_linear_attention"])
n("nfull", g["n_full_attention"])
n("nlinearqwen", g["n_linear_attention_qwen"])
n("nfullqwen", g["n_full_attention_qwen"])
n("inter", g["intermediate"])
n("vocab", g["vocab"])
n("vocabbase", g["vocab_base"])
n("vocabchip", g["vocab_chip"])
n("vocabstated", g["vocab_stated_sum"])
n("vocabresidual", g["vocab_residual"])
n("headdim", g["head_dim"])
n("lkeyheads", g["linear_num_key_heads"])
n("lvalheads", g["linear_num_value_heads"])
n("lkeydim", g["linear_key_head_dim"])
n("lvaldim", g["linear_value_head_dim"])
n("convk", g["conv_kernel"])
n("attnheads", g["num_attention_heads"])
n("kvheads", g["num_key_value_heads"])
s("arch", g["architecture"])
s("modeltype", g["model_type"])
s("sourcemodel", os.path.basename(g["source_model"]))
L.append("")

# ----------------------------------------------------------------- circuit
c = RES["circuit"]
L.append("// --- circuit ---")
n("irdims", c["ir_dims"])
n("circheads", c["heads"])
n("ffnunits", c["ffn_units"])
n("circlayers", c["layers"])
n("maxunits", c["max_units_per_layer"])
n("maxheads", c["max_heads_per_layer"])
n("codedims", c["code_dims"])
L.append("")

# -------------------------------------------------------------- parameters
p = RES["params"]
L.append("// --- parameters ---")
s("ptotal", f'{p["total_b"]:.2f}')
n("ptotalexact", p["total"])
s("pcard", f'{p["card_reports_b"]:.1f}')
s("pdelta", f'{p["delta_vs_card_b"]:+.2f}')
s("pgbdec", f'{p["gb_bf16_decimal"]:.1f}')
s("pgib", f'{p["gib_bf16_binary"]:.1f}')
s("pcardgb", f'{p["card_reports_gb"]:.0f}')
s("pchiplayers", f'{p["chip_layers_b"]:.2f}')
s("pqwennative", f'{p["qwen_native_b"]:.2f}')
s("pqwenwide", f'{p["qwen_widened_b"]:.2f}')
s("ppadding", f'{p["padding_b"]:.2f}')
s("pchipvocab", f'{p["chip_vocab_b"]:.2f}')
s("ppaddingpct", f'{p["padding_pct"]:.1f}')
s("plive", f'{p["live_b"]:.2f}')
n("nqwentensors", p["n_qwen_tensors"])
n("tensorsperchip", p["tensors_per_chip_layer"])
n("ntensorspred", p["predicted_total_tensors"])
n("ntensors", p["reported_total_tensors"])
s("tensorvalidated", "yes" if p["tensor_model_validated"] else "no")
s("paramcloses", "yes" if p["closes_against_total"] else "no")
s("pgatecost", f'{p["gate_cost_b"]:.2f}')
s("pnogate", f'{p["total_without_gate_b"]:.2f}')
L.append("")

# ------------------------------------------------------------ preservation
pr = RES["preservation"]
L.append("// --- weight preservation ---")
n("shaidentical", pr["identical"])
n("shanormresc", pr["norm_rescaled"])
n("shamismatch", pr["mismatches"])
n("shamissing", pr["missing"])
n("shapadnonzero", pr["pad_nonzero"])
n("shadropped", pr["dropped_vision_mtp"])
n("shachecked", pr["tensors_checked"])
L.append("")

# --------------------------------------------------------------- exactness
u = RES["upstream_4b"]
L.append("// --- upstream 4B reproduction ---")
n("upassed", u["passed"])
n("ufailed", u["failed"])
n("uskipped", u["skipped"])
s("ufailtest", u["failure_test"])
s("ufailkind", u["failure_kind"])
s("ucalcanswer", u["calc_answer"])
n("ucalcowned", u["calc_replay_owned"])
n("ucalcwrong", u["calc_replay_wrong"])
s("ucalctoks", f'{u["calc_chip_tok_per_s"]:.0f}')
s("ucommit", RES["attribution"]["upstream_commit"])
L.append("")

f = RES["freerun_27b"]
L.append("// --- circuit exactness at 27B ---")
n("tfpassed", f["teacher_forced_passed"])
n("tffailed", f["teacher_forced_failed"])
n("bridgepassed", f["bridge_tests_passed"])
n("fuzzprogs", f["fuzz_programs"])
n("fuzzinstr", f["fuzz_instructions"])
n("fuzztoks", f["fuzz_tokens"])
n("elfprogs", f["elf_programs"])
n("elfinstr", f["elf_instructions"])
n("elftoks", f["elf_tokens"])
n("totalprogs", f["total_programs"])
n("totalinstr", f["total_instructions"])
s("totalinstrm", f'{f["total_instructions"]/1e6:.2f}')
n("totaltoks", f["total_tokens"])
L.append("")

# ------------------------------------------------------------- the sweep
# Primary exactness evidence: one corpus, one run, one JSON per program, every
# figure recomputed by emit_results.py from those artifacts.
w = RES["sweep"]
L.append("// --- RV32IM sweep on the merged checkpoint (derived) ---")
n("swprogs", w["programs_ran"])
n("swexact", w["exact_chip_stream"])
n("swdiverged", w["diverged"])
n("swerrored", w["errored"])
n("swcprogs", w["c_programs"])
n("swcexact", w["c_programs_exact"])
n("swisa", w["isa_tests"])
n("swisaexact", w["isa_tests_exact"])
n("swinstr", w["instructions"])
s("swinstrm", f'{w["instructions"]/1e6:.2f}')
n("swtoks", w["tokens"])
n("swechoes", w["echoes"])
n("swechofail", w["echo_integrity_failures"])
n("swunhalted", w["did_not_halt"])
n("swrawexact", w["exact_raw_including_echoes"])
n("swprinting", w["printing_programs"])
n("swprintingraw", w["printing_raw_exact"])
n("swnonprinting", w["nonprinting_programs"])
n("swnonprintingraw", w["nonprinting_raw_exact"])
s("swexcessok", "yes" if w["token_excess_equals_echoes"] else "no")
s("swlongest", w["longest_program"])
n("swlongestinstr", w["longest_instructions"])
L.append("")

# ------------------------------------------------------------- end to end
e = RES["calc_e2e"]
L.append("// --- end to end calc ---")
s("calcanswer", e["answer"])
s("calcgrouped", e["answer_grouped"])
n("calctexttok", e["text_tokens"])
n("calcchiptok", e["chip_tokens"])
n("calcpositions", e["replay_positions"])
n("calcowned", e["replay_owned"])
n("calcwrong", e["replay_wrong"])
n("calcownermismatch", e["replay_owner_mismatch"])
L.append("")

L.append("// --- C programs on the merged checkpoint ---")
for name, d in RES["c_programs"].items():
    pre = f"c{name}"
    n(f"{pre}toks", d["tokens"])
    n(f"{pre}reftoks", d["reference_tokens"])
    s(f"{pre}tokdelta", f'{d["token_delta"]:+d}')
    n(f"{pre}instr", d["instructions"])
    s(f"{pre}exact", "yes" if d["exact"] else "no")
    s(f"{pre}chipexact", "yes" if d["exact_chip_stream"] else "no")
    n(f"{pre}echoes", d["echoes"])
    s(f"{pre}toksec", f'{d["tok_per_s"]:.0f}')
    if d["first_mismatch"] is not None:
        n(f"{pre}firstmismatch", d["first_mismatch"])
n("cprogsn", RES["c_programs_n"])
n("cprogsnexact", RES["c_programs_n_exact"])
s("cprogsallchipexact", "yes" if RES["c_programs_all_chip_streams_exact"] else "no")
s("gmpoutput", RES["c_programs"]["gmpmul"]["output"].replace("mul=", ""))
L.append("")

# ------------------------------------------------------------------- text
t = RES["text"]
L.append("// --- greedy text identity ---")
n("textn", t["n_prompts"])
n("textnew", t["n_new_tokens"])
n("textidentical", t["n_identical"])
n("textdivergent", t["n_divergent"])
s("textpositions", ", ".join(str(x) for x in t["divergence_positions"]))
s("textprompts", ", ".join(str(x) for x in t["divergent_prompt_ids"]))
s("textcriterion", "met" if t["criterion_met"] else "not met")
L.append("")

tf = RES["teacher_forced"]
L.append("// --- teacher-forced agreement ---")
n("tfpositions", tf["positions"])
n("tfagree", tf["top1_agree"])
n("tffloor", tf["harness_floor"])
s("tfabovefloor", f'{tf["above_floor"]:+d}')
s("tfklmean", f'{tf["kl_mean"]:.1e}'.replace("e-04", "e-4").replace("e-05", "e-5"))
s("tfklmax", f'{tf["kl_max"]:.1e}'.replace("e-02", "e-2"))
n("tfworstprompt", tf["worst_prompt"])
n("tfworstagree", tf["worst_prompt_agree"])
s("tfupstreamkl", "6e-4")
s("tfupstreamfloor", "5e-4")
L.append("")

# ------------------------------------------------------------------ speed
sp = RES["speed"]
L.append("// --- throughput on GB10 ---")
s("spexecb", f'{sp["executor_crc32_b1"]:,.0f}')
s("spexecbeight", f'{sp["executor_crc32_b8_total"]:,.0f}')
s("spexecbthirtytwo", f'{sp["executor_crc32_b32_total"]:,.0f}')
s("spexecbthirtytwostream", f'{sp["executor_crc32_b32_per_stream"]:,.0f}')
s("spexecinstr", f'{sp["executor_crc32_b1_instr_s"]:,.0f}')
s("spexecinstrthirtytwo", f'{sp["executor_crc32_b32_instr_s"]:,.0f}')
s("sptorchcompile", f'{sp["torch_compile_crc32_b1"]:,.0f}')
s("spexecgmp", f'{sp["executor_gmpmul_b1"]:,.0f}')
s("sphfcrc", f'{sp["hf_modules_crc32"]:.0f}')
s("sphfgmp", f'{sp["hf_modules_gmpmul"]:.0f}')
s("sphfstrops", f'{sp["hf_modules_strops"]:.0f}')
s("spchatfourb", f'{sp["chat_4b_executor"]:.0f}')
s("spchattwentyseven", f'{sp["chat_27b_streamed"]:.1f}')
s("spchatseconds", f'{sp["chat_27b_streamed_seconds"]/60:.0f}')
s("spbatchspeedup", f'{sp["batch32_speedup"]:.1f}')
s("spexecoverhf", f'{sp["executor_over_hf"]:.0f}')
s("spupstreaml", f'{sp["upstream_l4_reference"]:,}')
s("spmemneeded", f'{sp["gpu_memory_needed_gb"]:.0f}')
s("spallexact", "yes" if sp["all_bex_exact"] else "no")
L.append("")

# ------------------------------------------------------- criteria & machine
L.append("// --- acceptance criteria ---")
n("critmet", RES["criteria_met"])
n("crittotal", RES["criteria_total"])
n("critfailed", RES["criteria_total"] - RES["criteria_met"])
L.append("")

m = RES["machine"]
L.append("// --- machine ---")
n("romkb", m["code_rom_kb"])
n("rodatakb", m["rodata_kb"])
n("ramkb", m["ram_kb"])
s("isa", m["isa"])
s("host", m["host"])
L.append("")

a = RES["attribution"]
L.append("// --- attribution ---")
s("upproject", a["upstream_project"])
s("upauthor", a["upstream_author"])
s("upurl", a["upstream_url"])
s("upcode", a["upstream_code_license"])
s("upweights", a["upstream_weights_license"])
s("upinternal", a["upstream_internal_name"])
s("upbase", a["upstream_base_model"])
s("basemodel", a["base_model"])
s("hostmodel", a["host_model"])
s("companion", a["companion_paper"])
s("companionslug", a["companion_slug"])
L.append("")

# A criteria table the paper renders directly, so the pass/fail text cannot drift.
L.append("// --- criteria table rows (name, verdict, note) ---")
L.append("#let criteriarows = (")
for x in RES["criteria"]:
    nm = x["name"].replace('"', '\\"')
    note = x["note"].replace('"', '\\"')
    verdict = "met" if x["met"] else "not met"
    L.append(f'  ("{nm}", "{verdict}", "{note}"),')
L.append(")")
L.append("")

with open(OUT, "w") as fh:
    fh.write("\n".join(L))

defines = sum(1 for x in L if x.startswith("#let"))
print(f"wrote {OUT} ({defines} definitions)")
