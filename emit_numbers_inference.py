#!/usr/bin/env python3
"""Generate paper/inference.typ from results/inference.json. Nothing hand-typed.

Run after emit_inference.py. Same contract as emit_numbers.py: every figure the inference
section prints is defined here, so a re-run of the pipeline cannot leave a stale statistic
in the prose. Names are lowercase alphabetic for the Typst reasons documented in
emit_numbers.py.

Runs that have not finished yet are emitted as the string "pending" rather than omitted, so
the paper fails to compile on a missing definition instead of rendering a blank.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = json.load(open(os.path.join(HERE, "results", "inference.json")))
OUT = os.path.join(HERE, "paper", "inference.typ")
os.makedirs(os.path.dirname(OUT), exist_ok=True)

L = [
    "// GENERATED by emit_numbers_inference.py from results/inference.json — do not edit.",
    "// Every statistic in the inference section is defined here, so nothing is transcribed.",
    "",
]


def s(name, val):
    L.append(f'#let {name} = "{val}"')


def n(name, val):
    s(name, f"{val:,}")


def esc(t):
    """Printable form of a generation for inclusion in Typst source.

    A real newline in a generation is shown as a visible line break rather than an escape,
    so the reader sees what the model emitted; the prompt's trailing colon and the newline
    after it are part of the result.
    """
    return t.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " \u23ce ")


# ------------------------------------------------------------------- the machine
m = RES["machine"]
L.append("// --- inner-model memory budget ---")
n("infromkb", m["code_rom_kb"])
n("infrodatakb", m["rodata_kb"])
n("inframkb", m["ram_kb"])
L.append("")

# ------------------------------------------------------------------ op costs
L.append("// --- measured instruction cost per operation ---")
oc = RES["op_costs"]
n("opbaseline", oc["baseline_instructions"])
n("opiters", oc["iterations"])
for key, short in [("int8_mac", "int8mac"), ("float_mac", "floatmac"),
                   ("float_div", "floatdiv"), ("sqrtf", "sqrtf"), ("expf", "expf")]:
    d = oc["per_op"][key]
    s(f"op{short}", f'{d["instructions"]:.2f}')
    s(f"op{short}rel", f'{d["relative_to_int8_mac"]:.1f}')
L.append("")

fs = RES["float_softmax_cost"]
L.append("// --- what a float softmax would cost in the inner GPT ---")
n("fsexps", fs["exps_per_token"])
n("fsinstr", fs["instructions_per_token"])
n("fsmatmul", fs["matmul_instructions_per_token"])
s("fsratio", f'{fs["ratio_to_matmuls"]:.2f}')
L.append("")

# --------------------------------------------------------------------- the MLP
mm = RES["mlp_model"]
L.append("// --- inner model: MNIST MLP ---")
s("mlparch", mm["arch"])
n("mlpparams", mm["params_int8"])
s("mlprodatakb", f'{mm["rodata_bytes"] / 1024:.0f}')
n("mlprodatabytes", mm["rodata_bytes"])
s("mlpfloatacc", f'{mm["float_accuracy"] * 100:.2f}')
s("mlpintacc", f'{mm["int_accuracy"] * 100:.2f}')
s("mlpaccdelta", f'{mm["accuracy_delta"] * 100:.2f}')
n("mlpbatch", mm["batch_images"])
n("mlpbatchcorrect", mm["batch_correct"])
n("mlpshift", mm["requant_shift"])
L.append("")

mr = RES["mlp_run"]
L.append("// --- MLP on the merged checkpoint (HF module path) ---")
n("mlpinstr", mr["instructions"])
s("mlpinstrm", f'{mr["instructions"] / 1e6:.2f}')
n("mlptoks", mr["tokens"])
n("mlpreftoks", mr["reference_tokens"])
s("mlpexact", "yes" if mr["exact_chip_stream"] else "no")
n("mlpechoes", mr["echoes"])
s("mlpechook", "yes" if mr["echoes_equal_printed_bytes"] else "no")
s("mlphalted", "yes" if mr["halted"] else "no")
s("mlptoksec", f'{mr["tok_per_s"]:.0f}')
s("mlphours", f'{mr["seconds"] / 3600:.2f}')
s("mlpoutput", esc(mr["output"]))
L.append("")

me = RES["mlp_run_executor"]
L.append("// --- MLP through the Triton executor (cross-path check) ---")
if me is None:
    s("mlpexecexact", "pending")
    s("mlpexectoksec", "pending")
    s("mlpexecminutes", "pending")
    s("mlppathsagree", "pending")
    s("execspeedup", "pending")
else:
    s("mlpexecexact", "yes" if me["exact_chip_stream"] else "no")
    s("mlpexectoksec", f'{me["tok_per_s"]:.0f}')
    s("mlpexecminutes", f'{me["seconds"] / 60:.1f}')
    s("mlppathsagree", "yes" if RES["mlp_paths_agree"] else "no")
    s("execspeedup", f'{RES["executor_speedup_over_hf"]:.0f}')
L.append("")

# --------------------------------------------------------------------- the GPT
gm = RES["gpt_model"]
L.append("// --- inner model: character GPT ---")
s("gptarch", gm["arch"])
n("gptvocab", gm["vocab"])
n("gptlayers", gm["layers"])
n("gptdmodel", gm["d_model"])
n("gptheads", gm["heads"])
n("gptdff", gm["d_ff"])
n("gptctx", gm["ctx"])
n("gptparams", gm["params_int8"])
s("gptrodatakb", f'{gm["rodata_bytes"] / 1024:.0f}')
n("gptrodatabytes", gm["rodata_bytes"])
s("gptfloatloss", f'{gm["float_val_loss"]:.3f}')
s("gptintloss", f'{gm["int_val_loss"]:.3f}')
s("gptintbetter", "yes" if gm["int_beats_float"] else "no")
s("gptprompt", esc(gm["prompt"]))
s("gptfloatgen", esc(gm["float_generation"]))
s("gptspecgen", esc(gm["spec_generation"]))
n("gptsharedprefix", gm["float_int_shared_prefix_chars"])
n("gptncalib", gm["n_calibrated_tensors"])
n("gptnmul", gm["n_multipliers"])
s("gptcorpus", gm["corpus"])
L.append("")

for tag, key in [("four", "gpt4_run"), ("eight", "gpt8_run")]:
    r = RES[key]
    L.append(f"// --- GPT run: {key} ---")
    if r is None:
        for suffix in ["instr", "instrm", "toks", "reftoks", "exact", "echoes",
                       "halted", "toksec", "hours", "output"]:
            s(f"gpt{tag}{suffix}", "pending")
    else:
        n(f"gpt{tag}instr", r["instructions"])
        s(f"gpt{tag}instrm", f'{r["instructions"] / 1e6:.1f}')
        n(f"gpt{tag}toks", r["tokens"])
        n(f"gpt{tag}reftoks", r["reference_tokens"])
        s(f"gpt{tag}exact", "yes" if r["exact_chip_stream"] else "no")
        n(f"gpt{tag}echoes", r["echoes"])
        s(f"gpt{tag}halted", "yes" if r["halted"] else "no")
        s(f"gpt{tag}toksec", f'{r["tok_per_s"]:.0f}')
        s(f"gpt{tag}hours", f'{r["seconds"] / 3600:.2f}')
        s(f"gpt{tag}output", esc(r["output"]))
    L.append("")

qp = RES.get("quant_probe_chip")
L.append("// --- chip-layer weight-grid probe ---")
if qp is None:
    s("qpstate", "pending")
else:
    s("qpstate", "done")
    n("qptensors", qp["n_quantized_tensors"])
    n("qpexcluded", qp["n_excluded_tensors"])
    n("qpprogs", qp["n_programs"])
    s("qpcontrol", "yes" if qp["control_exact"] else "no")
    n("qplossy", qp["n_lossy_formats"])
    n("qplossyexact", qp["n_lossy_formats_exact"])
    n("qplossyprogsexact", qp["lossy_programs_exact"])
    s("qpsmallesterr", f'{qp["smallest_breaking_error"] * 100:.2f}')
L.append("")

rel = RES.get("release")
if rel is None:
    s("relstate", "pending")
else:
    s("relstate", "done")
    n("relnformats", rel["n_formats"])
    n("relnunchanged", rel["n_formats_machine_unchanged"])
    n("relnload", rel["n_formats_load"])
    n("relntextmeasured", rel["n_formats_text_measured"])
    s("relallunchanged", "yes" if rel["all_machine_unchanged"] else "no")
    s("relallload", "yes" if rel["all_load"] else "no")
    n("relmachinelayers", rel["machine_layers"])
    s("relrepo", rel["repo"])
    meth = rel.get("text_method") or {}
    if meth:
        n("reltextprompts", meth.get("prompts", 0))
        n("reltextnew", meth.get("new_tokens", 0))
    # One row per format: scheme, how the machine was checked, whether it held,
    # whether it loads, and the text figure or the reason there is none.
    cells = []
    for r in rel["formats"]:
        if r["text_measured"]:
            txt = f'{r["text_identical"]} of {r["text_prompts"]}'
        else:
            txt = "not measured"
        held = "yes" if r["machine_unchanged"] else "NO"
        basis = "sha256" if r["machine_basis"] == "sha256" else "dtype"
        cells.append(
            f'  ("{r["format"]}", "{r["scheme"]}", "{basis}", "{held}", '
            f'"{"yes" if r["loads"] else "no"}", "{txt}"),'
        )
    L.append("#let reltable = (")
    L.extend(cells)
    L.append(")")
    # The bf16 row carries the headline comparison against the base model.
    bf = next((r for r in rel["formats"] if r["format"] == "bf16"), None)
    if bf and bf["text_measured"]:
        n("relbftextident", bf["text_identical"])
        n("relbftextprompts", bf["text_prompts"])
        n("relbftextdiv", bf["text_median_first_divergence_char"])
L.append("")

rb = RES.get("release_build")
if rb is not None:
    n("rbmachine", rb["machine_tensors"])
    n("rbmachineident", rb["machine_identical"])
    n("rbvision", rb["vision_tensors"])
    n("rbmtp", rb["mtp_tensors"])
    n("rbnormf32", rb["norms_float32_instead_of_bf16"])
    n("rbtensorsrelease", rb["tensors_release_build"])
    n("rbtensorsmeasured", rb["tensors_measured_build"])
L.append("")

s("infnartifacts", RES["n_artifacts"])
s("infgenerated", RES["generated_utc"])

with open(OUT, "w") as fh:
    fh.write("\n".join(L) + "\n")

defines = sum(1 for x in L if x.startswith("#let"))
print(f"wrote {OUT} ({defines} definitions)")
pending = sum(1 for x in L if x.endswith('"pending"'))
if pending:
    print(f"  {pending} definitions pending (runs still in flight)")
