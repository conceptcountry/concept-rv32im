"""Generate the expected-token list from the emitted header, using exactly the C's arithmetic.

The header is the contract between training and the machine. Anything `train_gpt.py` holds
in process -- float scales, numpy dtypes, calibration tables -- is not what ships; the
int8 arrays and the (M0, shift) multipliers are. So the specification the C is checked
against must be derived from the header alone, which is what this script does.

Reads  gpt_weights.h
Writes gpt_expect.h  (g_expect), and prints the generation for the record.
"""
import json
import math
import pathlib
import re
import sys

import numpy as np

OUT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
hdr = (OUT / "gpt_weights.h").read_text()


def arr(name):
    m = re.search(r"\b" + name + r"\[\d+\] = \{([^}]*)\}", hdr)
    return np.array([int(v) for v in m.group(1).split(",")], dtype=np.int64)


def const(name):
    return int(re.search(r"#define " + name + r" (-?\d+)", hdr).group(1))


GV, GD, GL, GH, GHD, GFF, GT = (const(k) for k in ["GV", "GD", "GL", "GH", "GHD", "GFF", "GT"])
GNGEN, GNPROMPT = const("GNGEN"), const("GNPROMPT")
RN_PRE, RN_K, POS_NUM = const("RN_PRE"), const("RN_K"), const("POS_NUM")
m0, shv = arr("g_m0"), arr("g_sh")
MI = {k: const("MUL_" + k) for k in
      ["EMB", "NF"] + [f"{p}_{l}" for l in range(GL)
                       for p in ["N1", "N2", "Q", "K", "V", "SC", "O", "H", "M"]]}

tok = arr("g_tok").reshape(GV, GD)
pos = arr("g_pos").reshape(GT, GD)
wq = arr("g_wq").reshape(GL, GD, GD)
wk = arr("g_wk").reshape(GL, GD, GD)
wv = arr("g_wv").reshape(GL, GD, GD)
wo = arr("g_wo").reshape(GL, GD, GD)
w1 = arr("g_w1").reshape(GL, GFF, GD)
w2 = arr("g_w2").reshape(GL, GD, GFF)
gn1 = arr("g_gn1").reshape(GL, GD)
gn2 = arr("g_gn2").reshape(GL, GD)
gnf = arr("g_gnf")
gexp = arr("g_exp")
prompt = list(arr("g_prompt"))
chars = arr("g_chars")


def rq(a, i):
    return (np.asarray(a, np.int64) * m0[i]) >> shv[i]


def cl(a):
    return np.clip(a, -127, 127).astype(np.int64)


def rms(x, g, i):
    xs = np.asarray(x, np.int64) >> RN_PRE
    ss = int((xs * xs).sum())
    r = max(math.isqrt(ss // GD), 1)
    inv = (1 << RN_K) // r
    return cl(rq(xs * inv * g, i))


def forward(toks):
    """Mirrors forward() in gpt.c, with a cache cleared per call as the C does."""
    kc = np.zeros((GL, GT, GD), np.int64)
    vc = np.zeros((GL, GT, GD), np.int64)
    x = None
    for p, t in enumerate(toks):
        x = rq(tok[t] + ((pos[p] * POS_NUM) >> 10), MI["EMB"])
        for l in range(GL):
            n = rms(x, gn1[l], MI[f"N1_{l}"])
            q = cl(rq(n @ wq[l].T, MI[f"Q_{l}"]))
            k = cl(rq(n @ wk[l].T, MI[f"K_{l}"]))
            v = cl(rq(n @ wv[l].T, MI[f"V_{l}"]))
            kc[l, p], vc[l, p] = k, v
            att = np.zeros(GD, np.int64)
            for h in range(GH):
                sl = slice(h * GHD, (h + 1) * GHD)
                sc = rq(kc[l, : p + 1, sl] @ q[sl], MI[f"SC_{l}"])
                d = np.clip(int(sc.max()) - sc, 0, 255)
                pr = gexp[d]
                ps = max(int(pr.sum()), 1)
                att[sl] = cl((pr[:, None] * vc[l, : p + 1, sl]).sum(0) // ps)
            x = x + rq(att @ wo[l].T, MI[f"O_{l}"])
            n2 = rms(x, gn2[l], MI[f"N2_{l}"])
            hq = cl(np.maximum(rq(n2 @ w1[l].T, MI[f"H_{l}"]), 0))
            x = x + rq(hq @ w2[l].T, MI[f"M_{l}"])
    return rms(x, gnf, MI["NF"]) @ tok.T


seq = list(prompt)
for _ in range(GNGEN):
    seq.append(int(np.argmax(forward(seq))))

text = "".join(chr(chars[t]) for t in seq)
(OUT / "gpt_expect.h").write_text(
    "/* GENERATED by gen_expect.py from gpt_weights.h -- do not edit.\n"
    "   The expected token stream, derived with exactly the arithmetic gpt.c runs. */\n"
    "#pragma once\n#include <stdint.h>\n"
    f"static const uint8_t g_expect[{len(seq)}] = {{"
    + ",".join(str(int(t)) for t in seq) + "};\n")

meta_path = OUT / "gpt_meta.json"
meta = json.loads(meta_path.read_text())
meta["expected_tokens"] = [int(t) for t in seq]
meta["spec_generation"] = text
meta_path.write_text(json.dumps(meta, indent=1))

print("prompt   :", repr("".join(chr(chars[t]) for t in prompt)))
print("generated:", repr(text[GNPROMPT:]))
print("tokens   :", len(seq))
print("wrote gpt_expect.h")
